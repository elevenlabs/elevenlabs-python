import contextvars
import typing

from elevenlabs.realtime import ScribeRealtime
from elevenlabs.speech_to_text.client import AsyncSpeechToTextClient as AutogeneratedAsyncSpeechToTextClient
from elevenlabs.speech_to_text.client import SpeechToTextClient as AutogeneratedSpeechToTextClient
from elevenlabs.speech_to_text.raw_client import AsyncRawSpeechToTextClient, RawSpeechToTextClient

# Matches the sentinel used by Fern-generated clients for omitted optional params.
OMIT = typing.cast(typing.Any, ...)

# When set, STT convert requests rewrite the multipart `keyterms` field.
# Default OMIT means "do not rewrite" (other API calls share this http client).
_KEYTERMS_OVERRIDE: contextvars.ContextVar[typing.Any] = contextvars.ContextVar(
    "elevenlabs_stt_keyterms_override",
    default=OMIT,
)


def _apply_keyterms_override(data: typing.Optional[typing.Any]) -> typing.Optional[typing.Any]:
    """
    Fix keyterms multipart encoding.

    Fern currently JSON-encodes list form fields (`json.dumps([...])`), which
    sends a single `keyterms=["a","b"]` value. The Speech-to-Text API expects
    repeated form fields (`keyterms=a`, `keyterms=b`) and rejects the JSON
    string as exceeding the per-term 50-character limit.

    See https://github.com/elevenlabs/elevenlabs-python/issues/819
    """
    override = _KEYTERMS_OVERRIDE.get()
    if override is OMIT or not isinstance(data, dict) or "keyterms" not in data:
        return data

    data = dict(data)
    if override is None:
        # Generated code turns omitted keyterms into the literal string "null".
        data.pop("keyterms", None)
    else:
        data["keyterms"] = list(override)
    return data


class _HttpClientWithKeytermsFix:
    """Delegates to the Fern HttpClient, rewriting keyterms when an override is set."""

    def __init__(self, http_client: typing.Any) -> None:
        self._http_client = http_client

    def request(self, *args: typing.Any, **kwargs: typing.Any) -> typing.Any:
        if "data" in kwargs:
            kwargs["data"] = _apply_keyterms_override(kwargs["data"])
        return self._http_client.request(*args, **kwargs)

    def stream(self, *args: typing.Any, **kwargs: typing.Any) -> typing.Any:
        if "data" in kwargs:
            kwargs["data"] = _apply_keyterms_override(kwargs["data"])
        return self._http_client.stream(*args, **kwargs)

    def __getattr__(self, name: str) -> typing.Any:
        return getattr(self._http_client, name)


class _AsyncHttpClientWithKeytermsFix:
    """Async variant of `_HttpClientWithKeytermsFix`."""

    def __init__(self, http_client: typing.Any) -> None:
        self._http_client = http_client

    async def request(self, *args: typing.Any, **kwargs: typing.Any) -> typing.Any:
        if "data" in kwargs:
            kwargs["data"] = _apply_keyterms_override(kwargs["data"])
        return await self._http_client.request(*args, **kwargs)

    def stream(self, *args: typing.Any, **kwargs: typing.Any) -> typing.Any:
        if "data" in kwargs:
            kwargs["data"] = _apply_keyterms_override(kwargs["data"])
        return self._http_client.stream(*args, **kwargs)

    def __getattr__(self, name: str) -> typing.Any:
        return getattr(self._http_client, name)


class _RawSpeechToTextClientWithKeytermsFix:
    """Wraps the generated raw client so `convert` sends keyterms correctly."""

    def __init__(self, raw_client: RawSpeechToTextClient) -> None:
        self._raw_client = raw_client
        http = raw_client._client_wrapper.httpx_client
        if not isinstance(http, _HttpClientWithKeytermsFix):
            raw_client._client_wrapper.httpx_client = _HttpClientWithKeytermsFix(http)  # type: ignore[assignment]

    def __getattr__(self, name: str) -> typing.Any:
        return getattr(self._raw_client, name)

    def convert(self, *args: typing.Any, keyterms: typing.Any = OMIT, **kwargs: typing.Any) -> typing.Any:
        # OMIT/None => omit the field entirely; otherwise send repeated values.
        override = None if keyterms is OMIT else keyterms
        token = _KEYTERMS_OVERRIDE.set(override)
        try:
            return self._raw_client.convert(*args, keyterms=keyterms, **kwargs)
        finally:
            _KEYTERMS_OVERRIDE.reset(token)


class _AsyncRawSpeechToTextClientWithKeytermsFix:
    """Async wrap of the generated raw client so `convert` sends keyterms correctly."""

    def __init__(self, raw_client: AsyncRawSpeechToTextClient) -> None:
        self._raw_client = raw_client
        http = raw_client._client_wrapper.httpx_client
        if not isinstance(http, _AsyncHttpClientWithKeytermsFix):
            raw_client._client_wrapper.httpx_client = _AsyncHttpClientWithKeytermsFix(http)  # type: ignore[assignment]

    def __getattr__(self, name: str) -> typing.Any:
        return getattr(self._raw_client, name)

    async def convert(self, *args: typing.Any, keyterms: typing.Any = OMIT, **kwargs: typing.Any) -> typing.Any:
        override = None if keyterms is OMIT else keyterms
