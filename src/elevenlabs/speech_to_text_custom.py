import json
import typing

from elevenlabs.speech_to_text.client import SpeechToTextClient as AutogeneratedSpeechToTextClient
from elevenlabs.speech_to_text.client import AsyncSpeechToTextClient as AutogeneratedAsyncSpeechToTextClient
from elevenlabs.realtime import ScribeRealtime

# The generated raw client passes these multipart form fields through json.dumps, so a list
# arrives at the API as the single field keyterms='["hello", "world"]' instead of one field per
# item, a plain string arrives quoted, and an omitted field is sent as the literal "null".
# The encoding is undone here so the wire format matches what the API expects.
# See https://github.com/elevenlabs/elevenlabs-python/issues/819
_JSON_ENCODED_FORM_FIELDS = ("entity_detection", "entity_redaction", "keyterms", "webhook_metadata")

_DROP_FIELD = object()


def _decode_form_field(encoded: str) -> typing.Any:
    """Undo the JSON encoding of one form field, returning _DROP_FIELD if it should not be sent."""
    try:
        decoded = json.loads(encoded)
    except ValueError:
        return encoded
    if decoded is None:
        return _DROP_FIELD
    if isinstance(decoded, str):
        return decoded
    if isinstance(decoded, list):
        # httpx turns a list into one repeated form field per item.
        return [item if isinstance(item, str) else json.dumps(item) for item in decoded]
    # Objects, such as webhook_metadata, are expected as a JSON string.
    return encoded


def _decode_form_fields(data: typing.Any) -> typing.Any:
    if not isinstance(data, dict):
        return data
    decoded_data = dict(data)
    for name in _JSON_ENCODED_FORM_FIELDS:
        encoded = decoded_data.get(name)
        if not isinstance(encoded, str):
            continue
        decoded = _decode_form_field(encoded)
        if decoded is _DROP_FIELD:
            del decoded_data[name]
        else:
            decoded_data[name] = decoded
    return decoded_data


class _FormFieldDecodingHttpClient:
    """Delegates to the generated HTTP client after decoding JSON-encoded multipart fields."""

    def __init__(self, wrapped: typing.Any) -> None:
        self._wrapped = wrapped

    def __getattr__(self, name: str) -> typing.Any:
        return getattr(self._wrapped, name)

    def request(self, *args: typing.Any, **kwargs: typing.Any) -> typing.Any:
        if "data" in kwargs:
            kwargs["data"] = _decode_form_fields(kwargs["data"])
        return self._wrapped.request(*args, **kwargs)

    def stream(self, *args: typing.Any, **kwargs: typing.Any) -> typing.Any:
        if "data" in kwargs:
            kwargs["data"] = _decode_form_fields(kwargs["data"])
        return self._wrapped.stream(*args, **kwargs)


class _FormFieldDecodingClientWrapper:
    """Delegates to the shared client wrapper, but hands out a decoding HTTP client."""

    def __init__(self, wrapped: typing.Any) -> None:
        self._wrapped = wrapped
        self.httpx_client = _FormFieldDecodingHttpClient(wrapped.httpx_client)

    def __getattr__(self, name: str) -> typing.Any:
        return getattr(self._wrapped, name)


def _decode_form_fields_on_send(raw_client: typing.Any) -> None:
    raw_client._client_wrapper = _FormFieldDecodingClientWrapper(raw_client._client_wrapper)


class SpeechToTextClient(AutogeneratedSpeechToTextClient):
    """
    A client to handle ElevenLabs speech-to-text functionality.
    Extends the autogenerated client to include realtime transcription.
    """

    def __init__(self, **kwargs: typing.Any) -> None:
        super().__init__(**kwargs)
        self._realtime: typing.Optional[ScribeRealtime] = None
        _decode_form_fields_on_send(self._raw_client)

    @property
    def realtime(self) -> ScribeRealtime:
        """
        Access the realtime speech-to-text transcription API.

        Returns:
            ScribeRealtime instance for creating WebSocket connections

        Example:
            ```python
            from elevenlabs import ElevenLabs, RealtimeEvents, AudioFormat

            client = ElevenLabs(api_key="your-api-key")

            # URL-based streaming
            connection = await client.speech_to_text.realtime.connect({
                "url": "https://stream.example.com/audio.mp3"
            })

            connection.on(RealtimeEvents.PARTIAL_TRANSCRIPT, lambda data: print(data))

            # Manual audio chunks
            connection = await client.speech_to_text.realtime.connect({
                "audio_format": AudioFormat.PCM_16000,
                "sample_rate": 16000
            })
            ```
        """
        if not self._realtime:
            # Extract API key from client wrapper
            api_key = self._client_wrapper.get_headers().get("xi-api-key", "")
            base_url = self._client_wrapper.get_base_url()

            self._realtime = ScribeRealtime(api_key=api_key, base_url=base_url)
        return self._realtime


