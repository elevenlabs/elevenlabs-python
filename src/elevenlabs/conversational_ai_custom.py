class ConversationalAiClient(AutogeneratedConversationalAiClient):
    @property
    def tools(self) -> ToolsClient:
        if self._tools is None:
            self._tools = ToolsClient(client_wrapper=self._client_wrapper)
        return typing.cast(ToolsClient, self._tools)


class AsyncConversationalAiClient(AutogeneratedAsyncConversationalAiClient):
    @property
    def tools(self) -> AsyncToolsClient:
        if self._tools is None:
            self._tools = AsyncToolsClient(client_wrapper=self._client_wrapper)
