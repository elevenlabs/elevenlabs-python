ToolRequest = typing.Union[ToolRequestModel, ClientToolFunction]
"""What `tools.create()` and `tools.update()` accept: the request model, or a function decorated with
`@client_tool`. A chained tool builder is sent with `build()`."""


def _to_request(request: ToolRequest) -> ToolRequestModel:
    if isinstance(request, ClientToolFunction):
        return request.tool.build()
    if isinstance(request, Tool):
        raise TypeError(f"Call build() on the tool builder for {request.name!r} and pass the result as request=")
    return request


class ToolsClient(AutogeneratedToolsClient):
    def create(
        self, *, request: ToolRequest, request_options: typing.Optional[RequestOptions] = None
    ) -> ToolResponseModel:
        """Add a new tool to the available tools in the workspace.

        `request` can also be a `@client_tool` function.
        """
        return super().create(request=_to_request(request), request_options=request_options)

    def update(
        self, tool_id: str, *, request: ToolRequest, request_options: typing.Optional[RequestOptions] = None
    ) -> ToolResponseModel:
        """Update a tool that is available in the workspace.

        `request` can also be a `@client_tool` function.
        """
        return super().update(tool_id, request=_to_request(request), request_options=request_options)

    def check_client_tools(
        self,
        agent_id: str,
        *functions: ClientToolFunction,
        strict: bool = False,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> typing.List[ToolSchemaDrift]:
        """Compares `@client_tool` functions with the client tools the agent has on the server.

        Run it when your app starts, before `register_tools()`. It reports each function the agent has no tool for,
        and each param whose name, type, choices or required status differs, which would make the agent's calls
        fail or lose data. Each difference is issued as a `ToolSchemaDriftWarning` and returned; with
        `strict=True`, a `ToolSchemaDriftError` is raised instead.
        """
        tools: typing.List[ToolResponseModel] = []
        cursor: typing.Optional[str] = None
        while True:
            page = self.list(used_by_agent_id=agent_id, cursor=cursor, request_options=request_options)
            tools.extend(page.tools)
            if not page.has_more or not page.next_cursor:
                break
            cursor = page.next_cursor
        return report(compare_client_tools(functions, tools), strict)


