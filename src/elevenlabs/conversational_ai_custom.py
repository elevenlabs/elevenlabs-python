import typing

from .agent_tools.decorators import ClientToolFunction
from .agent_tools.tool import Tool
from .conversational_ai.client import AsyncConversationalAiClient as AutogeneratedAsyncConversationalAiClient
from .conversational_ai.client import ConversationalAiClient as AutogeneratedConversationalAiClient
from .conversational_ai.tools.client import AsyncToolsClient as AutogeneratedAsyncToolsClient
from .conversational_ai.tools.client import ToolsClient as AutogeneratedToolsClient
from .core.request_options import RequestOptions
from .types.tool_request_model import ToolRequestModel
from .types.tool_response_model import ToolResponseModel

ToolRequest = typing.Union[ToolRequestModel, ClientToolFunction]
"""What `tools.create()` and `tools.update()` accept: the request model, or a function decorated with
`@client_tool`. A chained tool builder is sent with `build()`."""


def _to_request(request: ToolRequest) -> ToolRequestModel:
    if isinstance(request, ClientToolFunction):
        return request.tool.build()
    if isinstance(request, Tool):
        raise TypeError(f"Call build() on the tool builder for {request.name!r} and pass the result as request=")
    return request


class ToolsClient(AutogeneratedToolsClient):
    def create(
        self, *, request: ToolRequest, request_options: typing.Optional[RequestOptions] = None
    ) -> ToolResponseModel:
        """Add a new tool to the available tools in the workspace.

        `request` can also be a `@client_tool` function.
        """
        return super().create(request=_to_request(request), request_options=request_options)

    def update(
        self, tool_id: str, *, request: ToolRequest, request_options: typing.Optional[RequestOptions] = None
    ) -> ToolResponseModel:
        """Update a tool that is available in the workspace.

        `request` can also be a `@client_tool` function.
        """
        return super().update(tool_id, request=_to_request(request), request_options=request_options)


class AsyncToolsClient(AutogeneratedAsyncToolsClient):
    async def create(
        self, *, request: ToolRequest, request_options: typing.Optional[RequestOptions] = None
    ) -> ToolResponseModel:
        """Add a new tool to the available tools in the workspace.

        `request` can also be a `@client_tool` function.
        """
        return await super().create(request=_to_request(request), request_options=request_options)

    async def update(
        self, tool_id: str, *, request: ToolRequest, request_options: typing.Optional[RequestOptions] = None
    ) -> ToolResponseModel:
        """Update a tool that is available in the workspace.

        `request` can also be a `@client_tool` function.
        """
        return await super().update(tool_id, request=_to_request(request), request_options=request_options)


class ConversationalAiClient(AutogeneratedConversationalAiClient):
    @property
    def tools(self) -> ToolsClient:
        if self._tools is None:
            self._tools = ToolsClient(client_wrapper=self._client_wrapper)
        return typing.cast(ToolsClient, self._tools)


class AsyncConversationalAiClient(AutogeneratedAsyncConversationalAiClient):
    @property
    def tools(self) -> AsyncToolsClient:
        if self._tools is None:
            self._tools = AsyncToolsClient(client_wrapper=self._client_wrapper)
        return typing.cast(AsyncToolsClient, self._tools)
