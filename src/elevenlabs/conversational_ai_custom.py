class AgentsClient(AutogeneratedAgentsClient):
    """`client.conversational_ai.agents`, with `push()` and `pull()` for agents written as code."""

    _tools_for_push: typing.Optional[AutogeneratedToolsClient] = None

    def push(
        self,
        agent: Agent,
        *,
        agent_id: typing.Optional[str] = None,
        project: typing.Optional[AgentProject] = None,
        branch_id: typing.Optional[str] = None,
        version_description: typing.Optional[str] = None,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> AgentPushResult:
        """Creates or updates an agent and every webhook and client tool it uses, in one call.

        1. Validates the agent, so an invalid one writes nothing.
        2. Creates each tool that's new and updates each one that changed. Which tools already exist comes from the
           project's `tools.json`, or, without a project, from the tools the agent (`agent_id`) already uses, by
           name: on its main branch, or on `branch_id` when given. Tools other agents use are never touched.
        3. Creates the agent, or updates it, with the tools' ids filled in.

        Settings the SDK doesn't model, kept from a loaded config, are sent too. Tools the agent stops using are
        reported as `"detached"`, not deleted.

        Parameters
        ----------
        agent : Agent
            The agent to push.

        agent_id : typing.Optional[str]
            The agent to update. Without it (and without a project that knows the agent), `push` creates a new
            agent, so keep the returned `agent_id`. Not allowed with `project`, which records the id itself.

        project : typing.Optional[AgentProject]
            An agents-as-code project in the CLI's layout. Its `agents.json` and `tools.json` say which agent and
            tools on the server this definition is; `push` records new ids there and writes the configs it sent,
            saving them if the project was opened from a directory.

        branch_id : typing.Optional[str]
            Update this branch of the agent instead of its main branch.

        version_description : typing.Optional[str]
            Describes the new version, for agents with versioning.

        request_options : typing.Optional[RequestOptions]
            Passed to every API call `push` makes.

        Returns
        -------
        AgentPushResult
            The agent's id, whether it was created or updated, and what happened to each tool.

        Raises
        ------
        AgentValidationError
            If the agent is invalid, before any API call.
        AgentPushError
            If an API call fails, with what was already written in `result`.

        Examples
        --------
        result = client.conversational_ai.agents.push(agent)
        client.conversational_ai.agents.push(agent, agent_id=result.agent_id)  # later: update it
        client.conversational_ai.agents.push(agent, project=project)  # or let a project track the ids
        """
        steps = push_steps(
            agent,
            agent_id=agent_id,
            project=project,
            branch_id=branch_id,
            version_description=version_description,
            request_options=request_options,
        )
        return run_sync(steps, self._push_clients())

    def pull(
        self,
        agent_id: str,
        *,
        project: typing.Optional[AgentProject] = None,
        branch_id: typing.Optional[str] = None,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> Agent:
        """Loads an existing agent as an `Agent`, with its webhook and client tools as `Tool` objects. With a project,
        also writes the agent and its tools there, in the CLI's layout, and records their ids.

        Parameters
        ----------
        agent_id : str
            The agent to load.

        project : typing.Optional[AgentProject]
            Writes the agent and its tools into this project, and records their ids.

        branch_id : typing.Optional[str]
            Pull this branch instead of the main one.

        request_options : typing.Optional[RequestOptions]
            Passed to every API call `pull` makes.

        Returns
        -------
        Agent

        Examples
        --------
        agent = client.conversational_ai.agents.pull(agent_id, project=project)
        agent.update(first_message="Hello!")
        client.conversational_ai.agents.push(agent, project=project)
        """
        steps = pull_steps(agent_id, project=project, branch_id=branch_id, request_options=request_options)
        return run_sync(steps, self._push_clients())

    def _push_clients(self) -> Clients:
        if self._tools_for_push is None:
            self._tools_for_push = AutogeneratedToolsClient(client_wrapper=self._client_wrapper)
        return Clients(agents=self, tools=self._tools_for_push)


