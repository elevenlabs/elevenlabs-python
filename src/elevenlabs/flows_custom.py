# this is used as the default value for optional parameters
OMIT = typing.cast(typing.Any, ...)

DEFAULT_MIN_POLL_INTERVAL_SECONDS = 1.0

_TERMINAL_STATUSES = frozenset({"completed", "failed"})

T = typing.TypeVar("T")


class FlowsWaitTimeoutError(Exception):
    """
    Raised by `create_and_wait` when a generation or template run is still unfinished after `timeout` seconds.

    The work keeps running on the server. Resume waiting by calling `get` with `id`
    (and `template_id` for a template run), or let a webhook deliver the result.
    """

    def __init__(
        self,
        *,
        id: str,
        timeout: float,
        last_response: typing.Any,
        template_id: typing.Optional[str] = None,
    ) -> None:
        self.id = id
        self.template_id = template_id
        self.timeout = timeout
        self.last_response = last_response
        kind = "Template run" if template_id is not None else "Generation"
        status = getattr(last_response, "status", None)
        super().__init__(f"{kind} {id} is still {status} after {timeout}s; call `get` with this id to keep waiting")


def _poll_delay(headers: typing.Mapping[str, str], min_interval: float) -> float:
    """Seconds to wait before the next GET: the server's `Retry-After`, never below `min_interval`, plus jitter."""
    retry_after = _parse_retry_after(httpx.Headers(headers))
    delay = max(retry_after if retry_after is not None else min_interval, min_interval)
    return _add_positive_jitter(delay)


def _is_terminal(response: typing.Any) -> bool:
    return getattr(response, "status", None) in _TERMINAL_STATUSES


def _wait(
    *,
    id: str,
    first_response: typing.Any,
    first_headers: typing.Mapping[str, str],
    get: typing.Callable[[], HttpResponse[T]],
    started_at: float,
    timeout: typing.Optional[float],
    min_interval: float,
    template_id: typing.Optional[str] = None,
) -> T:
    response: typing.Any = first_response
    headers = first_headers
    while not _is_terminal(response):
        delay = _poll_delay(headers, min_interval)
        if timeout is not None:
            remaining = started_at + timeout - time.monotonic()
            if remaining <= 0:
                raise FlowsWaitTimeoutError(id=id, timeout=timeout, last_response=response, template_id=template_id)
            delay = min(delay, remaining)
        time.sleep(delay)
        raw = get()
        response, headers = raw.data, raw.headers
    return typing.cast(T, response)


async def _async_wait(
    *,
    id: str,
    first_response: typing.Any,
    first_headers: typing.Mapping[str, str],
    get: typing.Callable[[], typing.Awaitable[AsyncHttpResponse[T]]],
    started_at: float,
    timeout: typing.Optional[float],
    min_interval: float,
    template_id: typing.Optional[str] = None,
) -> T:
    response: typing.Any = first_response
    headers = first_headers
    while not _is_terminal(response):
        delay = _poll_delay(headers, min_interval)
        if timeout is not None:
            remaining = started_at + timeout - time.monotonic()
            if remaining <= 0:
                raise FlowsWaitTimeoutError(id=id, timeout=timeout, last_response=response, template_id=template_id)
            delay = min(delay, remaining)
        await asyncio.sleep(delay)
        raw = await get()
        response, headers = raw.data, raw.headers
    return typing.cast(T, response)


_GENERATION_WAIT_DOC = """
        Start {article} {kind} generation and wait until it is `completed` or `failed`, then return the final generation.

        Between status checks this waits for the number of seconds in the server's `Retry-After` header,
        never less than `min_poll_interval`. This is meant for scripts and quickstarts: in production,
        set `webhook` on the request passed to `create` and handle the webhook event instead of holding a process open.

        A `failed` generation is returned, not raised; check `status` on the result.

        Parameters
        ----------
        request : {request_type}

        timeout : typing.Optional[float]
            Seconds to wait in total before raising `FlowsWaitTimeoutError`, which carries the generation `id`
            so you can resume with `get`. Waits indefinitely when omitted.

        min_poll_interval : float
            The shortest wait between status checks, in seconds. Also used when the server sends no `Retry-After`.

        request_options : typing.Optional[RequestOptions]
            Request-specific configuration, applied to the create call and every status check.

        Returns
        -------
        MediaGenerationResponse
            The generation in its terminal state.
"""


class ImageClient(AutogeneratedImageClient):
    def create_and_wait(
        self,
        *,
        request: ImageGenerationRequest,
        timeout: typing.Optional[float] = None,
        min_poll_interval: float = DEFAULT_MIN_POLL_INTERVAL_SECONDS,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> MediaGenerationResponse:
        started_at = time.monotonic()
        created = self.with_raw_response.create(request=request, request_options=request_options)
        generation_id = created.data.id
        return _wait(
            id=generation_id,
            first_response=created.data,
            first_headers=created.headers,
            get=lambda: self.with_raw_response.get(generation_id, request_options=request_options),
            started_at=started_at,
            timeout=timeout,
            min_interval=min_poll_interval,
        )

    create_and_wait.__doc__ = _GENERATION_WAIT_DOC.format(
        article="an", kind="image", request_type="ImageGenerationRequest"
    )


