_RUN_WAIT_DOC = """
        Start a run of a flows template and wait until its `status` is `completed` or `failed`, then return the final run.

        Between status checks this waits for the number of seconds in the server's `Retry-After` header,
        never less than `min_poll_interval`. This is meant for scripts and quickstarts: in production,
        pass `webhook` to `create` and handle the `flows_template_run` webhook instead of holding a process open.

        A `failed` run is returned, not raised; check `status` on the result and on each output.

        Parameters
        ----------
        template_id : str
            The ID of the template, as shown in the ElevenLabs app or by `GET /v1/flows/templates`.

        inputs : typing.Dict[str, TemplateRunInput]
            Input values keyed by input port id. Pass `{}` for a template with no inputs.

        version_id : typing.Optional[str]
            The template snapshot to run, or `latest` (the default when omitted).

        webhook : typing.Optional[WebhookTarget]
            Also send the run's result to the workspace's configured flows webhooks once it finishes.

        timeout : typing.Optional[float]
            Seconds to wait in total before raising `FlowsWaitTimeoutError`, which carries the run `id` and
            `template_id` so you can resume with `get`. Waits indefinitely when omitted.

        min_poll_interval : float
            The shortest wait between status checks, in seconds. Also used when the server sends no `Retry-After`.

        request_options : typing.Optional[RequestOptions]
            Request-specific configuration, applied to the create call and every status check.

        Returns
        -------
        TemplateRunResponse
            The run in its terminal state.
"""


class RunsClient(AutogeneratedRunsClient):
    def create_and_wait(
        self,
        template_id: str,
        *,
        inputs: typing.Dict[str, TemplateRunInput],
        version_id: typing.Optional[str] = OMIT,
        webhook: typing.Optional[WebhookTarget] = OMIT,
        timeout: typing.Optional[float] = None,
        min_poll_interval: float = DEFAULT_MIN_POLL_INTERVAL_SECONDS,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> TemplateRunResponse:
        started_at = time.monotonic()
        created = self.with_raw_response.create(
            template_id, inputs=inputs, version_id=version_id, webhook=webhook, request_options=request_options
        )
        run_id = created.data.id
        return _wait(
            id=run_id,
            template_id=template_id,
            first_response=created.data,
            first_headers=created.headers,
            get=lambda: self.with_raw_response.get(template_id, run_id, request_options=request_options),
            started_at=started_at,
            timeout=timeout,
            min_interval=min_poll_interval,
        )

    create_and_wait.__doc__ = _RUN_WAIT_DOC


