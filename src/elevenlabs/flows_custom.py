class RunsClient(AutogeneratedRunsClient):
    def create_and_wait(
        self,
        template_id: str,
        *,
        inputs: typing.Dict[str, TemplateRunInput],
        version_id: typing.Optional[str] = OMIT,
        webhook: typing.Optional[WebhookTarget] = OMIT,
        timeout: typing.Optional[float] = None,
        min_poll_interval: float = DEFAULT_MIN_POLL_INTERVAL_SECONDS,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> TemplateRunResponse:
        """
        Start a run of a flows template and wait until its `status` is `completed` or `failed`, then return the final run.

        Between status checks this waits as long as the server suggests, never less than `min_poll_interval`.
        This is meant for scripts and quickstarts: in production, pass `webhook` to `create` and handle the
        `flows_template_run` webhook instead of holding a process open.

        A `failed` run is returned, not raised; check `status` on the result and on each output.

        Parameters
        ----------
        template_id : str
            The ID of the template, as shown in the ElevenLabs app or by `GET /v1/flows/templates`.

        inputs : typing.Dict[str, TemplateRunInput]
            Input values keyed by input port id. Every input port of the version being run must be given; a missing or unknown id is rejected. Pass `{}` for a template with no inputs.

        version_id : typing.Optional[str]
            The template snapshot to run. Pass a specific version id to pin that snapshot, or `latest` (the default when omitted) to run the template's most recently published version. Only published versions can be pinned, except by the template's owner, who may also pin an unpublished saved snapshot to try it out before publishing. The live draft is never run through this API.

        webhook : typing.Optional[WebhookTarget]
            Include to send the run's result to the workspace's configured flows webhooks once the run's `status` reaches `completed` or `failed`. One event for the whole run: the `flows_template_run` event's `data` matches the terminal response of `GET /v1/flows/templates/{template_id}/runs/{run_id}`.

        timeout : typing.Optional[float]
            Seconds to wait in total before raising `FlowsWaitTimeoutError`, which carries the run `id` and `template_id`
            so you can resume with `get`. Waits indefinitely when omitted.

        min_poll_interval : float
            The shortest wait between status checks, in seconds, and the wait used when the server suggests none.
            Must be at least 0.5.

        request_options : typing.Optional[RequestOptions]
            Request-specific configuration, applied to the create call and to every status check, except
            `additional_body_parameters`, which only the create call gets. `timeout_in_seconds` and
            `max_retries` apply to each request on its own; use `timeout` to bound the whole wait.

        Returns
        -------
        TemplateRunResponse
            The run in its terminal state.
        """
        _check_min_poll_interval(min_poll_interval)
        started_at = time.monotonic()
        created = self.with_raw_response.create(
            template_id, inputs=inputs, version_id=version_id, webhook=webhook, request_options=request_options
        )
        run_id = created.data.id
        poll_options = _poll_request_options(request_options)
        return _wait(
            id=run_id,
            template_id=template_id,
            first_response=created.data,
            first_headers=created.headers,
            get=lambda: self.with_raw_response.get(template_id, run_id, request_options=poll_options),
            started_at=started_at,
            timeout=timeout,
            min_interval=min_poll_interval,
        )


