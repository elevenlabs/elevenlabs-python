class RunsClient(AutogeneratedRunsClient):
    def create_and_wait(
        self,
        template_id: str,
        *,
        inputs: typing.Dict[str, TemplateRunInput],
        version_id: typing.Optional[str] = OMIT,
        webhook: typing.Optional[WebhookTarget] = OMIT,
        timeout: typing.Optional[float] = None,
        min_poll_interval: float = DEFAULT_MIN_POLL_INTERVAL_SECONDS,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> TemplateRunResponse:
        _check_min_poll_interval(min_poll_interval)
        started_at = time.monotonic()
        created = self.with_raw_response.create(
            template_id, inputs=inputs, version_id=version_id, webhook=webhook, request_options=request_options
        )
        run_id = created.data.id
        poll_options = _poll_request_options(request_options)
        return _wait(
            id=run_id,
            template_id=template_id,
            first_response=created.data,
            first_headers=created.headers,
            get=lambda: self.with_raw_response.get(template_id, run_id, request_options=poll_options),
            started_at=started_at,
            timeout=timeout,
            min_interval=min_poll_interval,
        )

