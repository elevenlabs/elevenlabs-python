# this is used as the default value for optional parameters
OMIT = typing.cast(typing.Any, ...)

# Matches the server's shortest `Retry-After` (3s for image, audio and text), so the SDK polls no faster
# than the server would pace it when the header is missing.
DEFAULT_MIN_POLL_INTERVAL_SECONDS = 3.0

# Below this, a missing server hint would turn the wait into a tight loop of status checks.
_SMALLEST_MIN_POLL_INTERVAL_SECONDS = 0.5

# Spreads out clients that started together so their status checks don't arrive in lockstep.
_POLL_JITTER = 0.2

_TERMINAL_STATUSES = frozenset({"completed", "failed"})

T = typing.TypeVar("T")

TerminalMediaGenerationResponse = typing.Union[MediaGenerationResponse_Completed, MediaGenerationResponse_Failed]
"""What `create_and_wait` returns for a generation: always `completed` or `failed`, never in progress."""


class FlowsWaitTimeoutError(Exception):
    """
    Raised by `create_and_wait` when a generation or template run is still unfinished after `wait_timeout_in_seconds` seconds.

    The work keeps running on the server. Resume waiting by calling `get` with `id`
    (and `template_id` for a template run), or let a webhook deliver the result.
    """

    def __init__(
        self,
        *,
        id: str,
        wait_timeout_in_seconds: float,
        last_response: typing.Any,
        template_id: typing.Optional[str] = None,
    ) -> None:
        self.id = id
        self.template_id = template_id
        self.wait_timeout_in_seconds = wait_timeout_in_seconds
        self.last_response = last_response
        status = getattr(last_response, "status", None)
        if template_id is not None:
            message = (
                f"Template run {id} of template {template_id} is still {status} after {wait_timeout_in_seconds}s; "
                "call `runs.get` with `template_id` and `id` to keep waiting"
            )
        else:
            message = f"Generation {id} is still {status} after {wait_timeout_in_seconds}s; call `get` with this id to keep waiting"
        super().__init__(message)


def _check_wait_options(wait_timeout_in_seconds: typing.Optional[float], min_interval: float) -> None:
    # NaN passes every `<` check, and an infinite interval would never poll, so both are rejected explicitly.
    if not math.isfinite(min_interval) or min_interval < _SMALLEST_MIN_POLL_INTERVAL_SECONDS:
        raise ValueError(
            f"min_poll_interval_in_seconds must be a finite number of at least {_SMALLEST_MIN_POLL_INTERVAL_SECONDS}s, got {min_interval}"
        )
    # Written as `not >= 0` so NaN fails too: a NaN deadline never compares as passed, so the wait would
    # silently ignore the timeout. 0 times out straight after the create; None or inf waits indefinitely.
    if wait_timeout_in_seconds is not None and not wait_timeout_in_seconds >= 0:
        raise ValueError(f"wait_timeout_in_seconds must be at least 0s, got {wait_timeout_in_seconds}")


def _poll_request_options(request_options: typing.Optional[RequestOptions]) -> typing.Optional[RequestOptions]:
    """The caller's options for the status GETs: everything except body parameters, which only the create takes."""
    if request_options is None or "additional_body_parameters" not in request_options:
        return request_options
    return typing.cast(RequestOptions, {k: v for k, v in request_options.items() if k != "additional_body_parameters"})


def _parse_retry_after(headers: typing.Mapping[str, str]) -> typing.Optional[float]:
    """
    Seconds from a `Retry-After` header, given as whole seconds or an HTTP date (RFC 9110), or None if absent
    or unparseable. Kept here rather than imported from the generated `core.http_client`, whose private
    helpers can change on any regeneration.
    """
    value = next((v for k, v in headers.items() if k.lower() == "retry-after"), None)
    if value is None:
        return None
    value = value.strip()
    if value.isdigit():
        return float(value)
    try:
        retry_date = email.utils.parsedate_to_datetime(value)
    except (TypeError, ValueError):
        return None
    if retry_date is None:  # Python < 3.10 returns None instead of raising
        return None
    return max(retry_date.timestamp() - time.time(), 0.0)


def _poll_delay(headers: typing.Mapping[str, str], min_interval: float) -> float:
    """Seconds to wait before the next GET: the server's `Retry-After`, never below `min_interval`, plus 0-20% jitter."""
    retry_after = _parse_retry_after(headers)
    delay = max(retry_after if retry_after is not None else min_interval, min_interval)
    return delay * (1 + random() * _POLL_JITTER)


def _is_terminal(response: typing.Any) -> bool:
    return getattr(response, "status", None) in _TERMINAL_STATUSES


def _wait(
    *,
    id: str,
    first_response: typing.Any,
    first_headers: typing.Mapping[str, str],
    get: typing.Callable[[], HttpResponse[T]],
    started_at: float,
    wait_timeout_in_seconds: typing.Optional[float],
    min_interval: float,
    template_id: typing.Optional[str] = None,
) -> T:
    response: typing.Any = first_response
    headers = first_headers
    while not _is_terminal(response):
        delay = _poll_delay(headers, min_interval)
        if wait_timeout_in_seconds is not None:
            # The last sleep ends on the deadline; the GET after it takes time, so the next pass raises.
            remaining = started_at + wait_timeout_in_seconds - time.monotonic()
            if remaining <= 0:
                raise FlowsWaitTimeoutError(
                    id=id,
                    wait_timeout_in_seconds=wait_timeout_in_seconds,
                    last_response=response,
                    template_id=template_id,
                )
            delay = min(delay, remaining)
        time.sleep(delay)
        raw = get()
        response, headers = raw.data, raw.headers
    return typing.cast(T, response)


async def _async_wait(
    *,
    id: str,
    first_response: typing.Any,
    first_headers: typing.Mapping[str, str],
    get: typing.Callable[[], typing.Awaitable[AsyncHttpResponse[T]]],
    started_at: float,
    wait_timeout_in_seconds: typing.Optional[float],
    min_interval: float,
    template_id: typing.Optional[str] = None,
) -> T:
    response: typing.Any = first_response
    headers = first_headers
    while not _is_terminal(response):
        delay = _poll_delay(headers, min_interval)
        if wait_timeout_in_seconds is not None:
            # The last sleep ends on the deadline; the GET after it takes time, so the next pass raises.
            remaining = started_at + wait_timeout_in_seconds - time.monotonic()
            if remaining <= 0:
                raise FlowsWaitTimeoutError(
                    id=id,
                    wait_timeout_in_seconds=wait_timeout_in_seconds,
                    last_response=response,
                    template_id=template_id,
                )
            delay = min(delay, remaining)
        await asyncio.sleep(delay)
        raw = await get()
        response, headers = raw.data, raw.headers
    return typing.cast(T, response)


class ImageClient(AutogeneratedImageClient):
    def create_and_wait(
        self,
        *,
        request: ImageGenerationRequest,
        wait_timeout_in_seconds: typing.Optional[float] = None,
        min_poll_interval_in_seconds: float = DEFAULT_MIN_POLL_INTERVAL_SECONDS,
        request_options: typing.Optional[RequestOptions] = None,
    ) -> TerminalMediaGenerationResponse:
        """
        Start an image generation and wait until it is `completed` or `failed`, then return the final generation.

        Between status checks this waits as long as the server suggests, never less than `min_poll_interval_in_seconds`.
        This is meant for scripts and quickstarts: in production, set `webhook` on the request passed to `create`
        and handle the webhook event instead of holding a process open.

        A `failed` generation is returned, not raised; check `status` on the result.

        Parameters
        ----------
        request : ImageGenerationRequest

        wait_timeout_in_seconds : typing.Optional[float]
            Seconds to wait in total before raising `FlowsWaitTimeoutError`, which carries the generation `id`
            so you can resume with `get`. Waits indefinitely when omitted or `float("inf")`; must be at least 0
            when set. Not to be confused with the client's `timeout` or `timeout_in_seconds` in
            `request_options`, which limit each HTTP request.

        min_poll_interval_in_seconds : float
            The shortest wait between status checks, in seconds, and the wait used when the server suggests none.
            Must be at least 0.5.

        request_options : typing.Optional[RequestOptions]
            Request-specific configuration, applied to the create call and to every status check, except
            `additional_body_parameters`, which only the create call gets. `timeout_in_seconds` and
            `max_retries` apply to each request on its own; `wait_timeout_in_seconds` bounds the whole wait.

        Returns
        -------
        TerminalMediaGenerationResponse
            The generation in its terminal state: `MediaGenerationResponse_Completed` or `MediaGenerationResponse_Failed`.
        """
        _check_wait_options(wait_timeout_in_seconds, min_poll_interval_in_seconds)
        started_at = time.monotonic()
        created = self.with_raw_response.create(request=request, request_options=request_options)
        generation_id = created.data.id
        poll_options = _poll_request_options(request_options)
        return typing.cast(
            TerminalMediaGenerationResponse,
            _wait(
                id=generation_id,
                first_response=created.data,
                first_headers=created.headers,
                get=lambda: self.with_raw_response.get(generation_id, request_options=poll_options),
                started_at=started_at,
                wait_timeout_in_seconds=wait_timeout_in_seconds,
                min_interval=min_poll_interval_in_seconds,
            ),
        )


